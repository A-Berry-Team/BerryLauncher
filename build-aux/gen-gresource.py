#!/usr/bin/env python3
"""Generate berrylauncher.gresource.xml from the contents of src/resources/.

Images are bundled automatically; no manifest edits needed.

    src/resources/icons/...    -> icons/...
    src/resources/<other>/...  -> resources/<other>/...

Usage: gen-gresource.py <resources-dir> <output.xml>
The output is only rewritten when its content changes.
"""
import os
import sys
from xml.sax.saxutils import quoteattr

PREFIX = "/app/berrylauncher/berry"
IMAGE_EXTENSIONS = {
    ".svg", ".png", ".jpg", ".jpeg", ".webp", ".avif", ".gif", ".bmp", ".tif", ".tiff",
}


def collect(resources_dir):
    entries = []
    for root, _dirs, files in os.walk(resources_dir):
        for name in files:
            path = os.path.join(root, name)
            rel = os.path.relpath(path, resources_dir).replace(os.sep, "/")
            if os.path.splitext(name)[1].lower() not in IMAGE_EXTENSIONS:
                print(f"gen-gresource: skipping unsupported file {rel}", file=sys.stderr)
                continue
            alias = rel if rel.startswith("icons/") else f"resources/{rel}"
            entries.append((alias, f"resources/{rel}"))
    return sorted(entries)


def render(entries):
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- Generated by build-aux/gen-gresource.py. Do not edit. -->",
        "<gresources>",
        f"  <gresource prefix={quoteattr(PREFIX)}>",
    ]
    for alias, source in entries:
        lines.append(f"    <file alias={quoteattr(alias)}>{source.replace('&', '&amp;')}</file>")
    lines += ["  </gresource>", "</gresources>", ""]
    return "\n".join(lines)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    resources_dir, output = sys.argv[1], sys.argv[2]
    text = render(collect(resources_dir))
    try:
        with open(output, encoding="utf-8") as handle:
            if handle.read() == text:
                return
    except FileNotFoundError:
        pass
    with open(output, "w", encoding="utf-8") as handle:
        handle.write(text)


if __name__ == "__main__":
    main()
